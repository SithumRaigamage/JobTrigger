/// PI-03 / IMP-35: the destination of the "Why can't I reach it?" action on
/// [ConnectionErrorView]. With a [diagnosis] (passed as route `extra`) it
/// leads with the likely cause; either way it lists all five common causes
/// generated by the same pure function, so the copy has one source.
class ConnectionHelpScreen extends StatelessWidget {
  const ConnectionHelpScreen({super.key, this.diagnosis});

  final ConnectionDiagnosis? diagnosis;

  @override
  Widget build(BuildContext context) {
    final textTheme = Theme.of(context).textTheme;
    final checklist = connectionChecklist();
    final causes = diagnosis == null
        ? checklist
        : [
            diagnosis!,
            ...checklist.where((item) => item.cause != diagnosis!.cause),
          ];

    return Scaffold(
      appBar: AppBar(
        title: const Text("Why can't I reach it?"),
        leading: IconButton(
          icon: const Icon(Icons.chevron_left_rounded),
          tooltip: 'Back',
          onPressed: () => context.pop(),
        ),
      ),
      body: SafeArea(
        child: ResponsiveCenter(
          child: SingleChildScrollView(
            padding: const EdgeInsets.fromLTRB(20, 12, 20, 24),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                Text(
                  'Connection problems usually come down to the address, the '
                  'network the phone is on, or the server’s certificate. '
                  'These are checks, not detections — the app can’t see which '
                  'network you’re using.',
                  style: textTheme.bodyMedium,
                ),
                if (diagnosis != null) ...[
                  const SizedBox(height: 16),
                  InlineAlert(
                    tone: StatusTone.neutral,
                    icon: Icons.lightbulb_outline_rounded,
                    title: 'Likely cause: ${diagnosis!.title}',
                    message: diagnosis!.explanation,
                  ),
                ],
                const SizedBox(height: 20),
                Semantics(
                  header: true,
                  child: Text('WHAT TO CHECK', style: textTheme.labelLarge),
                ),
                const SizedBox(height: 8),
                for (final cause in causes) _CauseCard(cause: cause),
                const SizedBox(height: 4),
                ListTile(
                  minTileHeight: 56,
                  leading: const Icon(Icons.menu_book_rounded),
                  title: const Text('Remote access guide'),
                  subtitle: const Text(
                    'Tailscale, WireGuard and Cloudflare Tunnel, step by step',
                  ),
                  trailing: const Icon(Icons.chevron_right_rounded),
                  onTap: () => context.push(AppRoutes.remoteAccessGuide),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }
}

class _CauseCard extends StatelessWidget {
  const _CauseCard({required this.cause});

  final ConnectionDiagnosis cause;

  @override
  Widget build(BuildContext context) {
    final t = AppTokens.of(context);
    final textTheme = Theme.of(context).textTheme;
    return Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: DecoratedBox(
        decoration: BoxDecoration(
          color: t.card,
          borderRadius: BorderRadius.circular(16),
          border: Border.all(color: t.cardBorder),
        ),
        child: Padding(
          padding: const EdgeInsets.all(16),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Semantics(
                header: true,
                child: Text(
                  cause.title,
                  style: textTheme.titleSmall?.copyWith(
                    fontWeight: FontWeight.bold,
                  ),
                ),
              ),
              const SizedBox(height: 8),
              Text(cause.explanation, style: textTheme.bodyMedium),
              const SizedBox(height: 8),
              for (final tip in cause.fixTips)
                Padding(
                  padding: const EdgeInsets.only(top: 4),
                  child: Row(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Icon(Icons.check_rounded, size: 16, color: t.textMuted),
                      const SizedBox(width: 8),
                      Expanded(child: Text(tip, style: textTheme.bodyMedium)),
                    ],
                  ),
                ),
            ],
          ),
        ),
      ),
    );
  }
}
